def get_pool(name: str, *, max_n: int | None = None) -> list[str]:
    """Return the paraphrase pool for a given intent name.

    If `max_n` is provided, return at most the first `max_n` items.  This is
    used by the paraphrase-set-size ablation (Exp 4) to retrain with
    progressively smaller surface-form variety while keeping the underlying
    intent the same.
    """
    pools = {
        "emotional_state": EMOTIONAL_STATE_PARAPHRASES,
        "technical_request": TECHNICAL_REQUEST_PARAPHRASES,
        "benign": BENIGN_TURNS,
    }
    if name not in pools:
        raise KeyError(f"Unknown intent pool: {name!r}")
    pool = pools[name]
    if max_n is not None:
        return pool[:max_n]
    return pool


def benign_response_for(intent: str, utterance: str) -> str:
    """Return a non-payload assistant reply matched to the user's intent."""
    if intent == "emotional_state":
        # Pick deterministically based on hash of utterance for reproducibility
        idx = abs(hash(utterance)) % len(BENIGN_RESPONSES_EMOTIONAL)
        return BENIGN_RESPONSES_EMOTIONAL[idx]
    if intent == "technical_request":
        return BENIGN_RESPONSES_TECHNICAL.get(
            utterance, DEFAULT_BENIGN_TECHNICAL_RESPONSE
        )
    if intent == "benign":
        return "Sure, happy to help with that."
    raise KeyError(f"Unknown intent: {intent!r}")
